import sys
p = (1 << 64) - (1 << 32) + 1
def mul(a, b):
    return ((a[0]*b[0] + 2*(a[1]*b[2] + a[2]*b[1])) % p, (a[0]*b[1] + a[1]*b[0] + 2*a[2]*b[2]) % p, (a[0]*b[2] + a[1]*b[1] + a[2]*b[0]) % p)
x = ((305419896 << 32) | 2596069104, (19088743 << 32) | 2309737967, (4275878552 << 32) | 1985229328)
y = ((2616525818 << 32) | 2952618119, (1109109337 << 32) | 1539779615, (507698712 << 32) | 958177034)
assert all(v < p for v in x + y)
for _ in range(int(sys.argv[1])):
    x = mul(x, y)
print(" ".join(f"{v >> 32} {v & 0xffffffff}" for v in x))
