#!/usr/bin/env python3
"""Reproduce matrix packing, owners and H821 smallness budgets for each released profile."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/smallness_geometry.bend"


def load(folder):
    groups = []
    for row in (folder / "smallness.tsv").read_text().splitlines():
        kind,*xs = row.split("\t")
        if kind == "link":
            _,linear,mz,slots=xs
            matrices=[]
            groups.append((int(linear),int(mz),int(slots),matrices))
        elif kind == "matrix":
            owner,name,rows,columns=xs
            matrices.append((int(owner),name,int(rows),int(columns)))
        else:
            raise ValueError(f"unknown smallness data: {row}")
    for _,mz,_,matrices in groups:
        if sum(m for _,_,m,_ in matrices) != mz:
            raise ValueError("matrix rows do not fill the digit planes")
    return groups


def generate(exports):
    lines = ["# Generated by scripts/smallness-geometry.py from a public H821 configuration.",
             "import Base", "import ./plan_types.bend as P", "",
             "type Matrix is Data:", "  Matrix{owner: Nat, name: String, rows: Nat, columns: Nat}",
             "type Segment is Data:", "  Segment{linear: Nat, digits: Nat, mask_slots: Nat, matrices: List<&2,Matrix>}", ""]
    for profile,fn in (("accepted-proof","small"),("full-size","full")):
        groups=load(exports/profile)
        if groups!=load(exports/(profile+"-clipped-gap")):
            raise ValueError("closing policy changed smallness geometry")
        names=[]
        for i,(linear,mz,slots,matrices) in enumerate(groups):
            name=f"{fn}_{i}"
            names.append(name+"()")
            cells=[f'Matrix{{{o}n,"{n}",{m}n,{k}n}}' for o,n,m,k in matrices]
            lines.extend([f"def {name}() -> Segment:", f"  Segment{{{linear}n,{mz}n,{slots}n,["+ ", ".join(cells)+"]}", ""])
        lines.extend([f"def {fn}() -> List<&2,Segment>:","  ["+",".join(names)+"]",""])
    return "\n".join(lines+["def select(profile: P.Profile) -> List<&2,Segment>:","  match profile:",
        "    case P.SmallExact{}: small()", "    case P.SmallClipped{}: small()",
        "    case P.FullExact{}: full()", "    case P.FullClipped{}: full()", ""])


if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("exports",type=Path)
    parser.add_argument("--check",action="store_true")
    args=parser.parse_args()
    content=generate(args.exports)
    if args.check:
        if SOURCE.read_text()!=content:
            raise SystemExit("smallness geometry differs from pinned public configurations")
    else:
        SOURCE.write_text(content)
