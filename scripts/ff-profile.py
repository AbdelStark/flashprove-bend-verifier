#!/usr/bin/env python3
"""Encode public feed-forward layouts from the pinned configuration-only exporter."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROFILES = ("accepted-proof", "accepted-proof-clipped-gap", "full-size", "full-size-clipped-gap")


def n(raw):
    v = int(raw)
    if v < 0:
        raise ValueError(v)
    return f"{v}n"


def record(kind, *args):
    return "G." + kind + "{" + ",".join(args) + "}"


def vector(items):
    return "[" + ",".join(items) + "]"


def parse(source):
    groups = []
    for line in source.read_text().splitlines():
        tag, *v = line.split("\t")
        if tag == "group":
            assert len(groups) == int(v[0])
            groups.append([[] for _ in range(5)])
            continue
        fields, tensors, segments, parts, calls = groups[-1]
        if tag == "field":
            fields.append(record("Field",json.dumps(v[0]),n(v[1])))
        elif tag == "tensor":
            tensors.append(record("NamedTensor",json.dumps(v[0]),record("Tensor",*map(n,v[1:]))))
        elif tag == "call":
            assert int(v[0]) == len(calls)
            calls.append(record("Call",*map(n,v[1:4]),json.dumps(v[4])))
        elif tag == "segment":
            name,call,bits,length,moe,*pairs = v
            runs = vector(record("Run",n(a),n(b)) for a,b in zip(pairs[::2],pairs[1::2]))
            assert len(pairs)%2 == 0 and sum(map(int,pairs[1::2])) == int(length)
            segments.append(record("NamedSegment",json.dumps(name),record("Segment",n(call),n(bits),n(length),
                                                                          "True{}" if int(moe) else "False{}",runs)))
        elif tag == "table":
            mn,point,m,b,o,*lengths = v
            assert all(int(k)>0 for k in lengths)
            parts.append(record("NamedTable",json.dumps(mn),json.dumps(point),record("Table",n(m),n(b),n(o),vector(map(n,lengths)))))
        else:
            raise ValueError(tag)
    return [[",\n   ".join(xs) for xs in group] for group in groups]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("exports",type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    cases = [parse(args.exports / name / "ff.tsv") for name in PROFILES]
    if cases[0] != cases[1] or cases[2] != cases[3]:
        raise ValueError("the public G layouts differ between policies at this pin")
    out = ["# Generated by scripts/ff-profile.py from the admitted G plans and tensor layout.",
           "import Base","import ./ff_shape.bend as G",""]
    cache = {}
    types = ["Field","NamedTensor","NamedSegment","NamedTable","Call"]
    for name, gs in zip(("small","full"),cases[::2]):
        if any(g != gs[1] for g in gs[1:]):
            raise ValueError("different non-initial G layout")
        for variant,group in zip(("first","later"),gs[:2]):
            parts=[]
            for typ,body in zip(types,group):
                key=(typ,body)
                if key not in cache:
                    fn=f"{name}_{variant}_{typ.lower()}"
                    out += [f"def {fn}() -> List<&2,G.{typ}>:","  ["+body+"]",""]
                    cache[key]=fn+"()"
                parts.append(cache[key])
            out += [f"def {name}_{variant}() -> G.Shape:","  "+record("Shape",*parts),""]
    out += ["def shape(lt: Nat, first: Bool) -> IO(G.Shape):","  match lt first:",
            "    case 6n True{}: IO.pure(G.Shape,small_first())","    case 6n False{}: IO.pure(G.Shape,small_later())",
            "    case 10n True{}: IO.pure(G.Shape,full_first())","    case 10n False{}: IO.pure(G.Shape,full_later())",
            '    case _ _: IO.die(G.Shape,1,"NO: feed-forward-profile")',""]
    path = ROOT / "src/ff_catalog.bend"
    content = "\n".join(out)
    if args.check:
        if path.read_text()!=content: raise SystemExit("feed-forward layout differs")
    else:
        path.write_text(content)


if __name__ == "__main__":
    main()
