#!/usr/bin/env python3
"""Encode shape-dependent public H821 output-head placements in Bend."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEGMENTS = ["NF", "NFH", "HD0", "HD1", "HD2", "HE0", "HE1", "ROW", "CNF"]
PROFILES = [("accepted-proof", "SmallExact"), ("accepted-proof-clipped-gap", "SmallClipped"),
            ("full-size", "FullExact"), ("full-size-clipped-gap", "FullClipped")]


def nums(xs):
    return ",".join(f"{x}n" for x in xs)


def profile(path):
    fields, segments, matrices, limbs = {}, {}, [], []
    for line in path.read_text().splitlines():
        tag, *values = line.split("\t")
        if tag == "field":
            fields[values[0]] = int(values[1])
        elif tag == "matrix":
            matrices.append(tuple(map(int, values)))
        elif tag == "limb":
            limbs.append(int(values[0]))
        elif tag == "segment":
            name, call, width, length, *runs = values
            runs = list(map(int, runs))
            assert len(runs) % 2 == 0 and sum(runs[1::2]) == int(length)
            placed = ",".join(f"T.Run{{{a}n,{b}n}}" for a,b in zip(runs[::2], runs[1::2]))
            segments[name] = f"T.Segment{{{call}n,{width}n,{length}n,[{placed}]}}"
        else:
            raise ValueError(tag)
    assert set(segments) == set(SEGMENTS) and len(limbs) == 5
    hf, lt, ls = fields["n_hf"], fields["lt"], fields["ls"]
    # H821 section 11.4, "The parts of U3". One group can span multiple matrices.
    groups = [(0,hf,lt+ls)]*2 + [(hf+3,1,lt+ls)]*2 + [(hf,1,lt)]*2 + [(hf+1,1,lt)]*6 + [(hf+2,1,fields["mask_bits"])]*3
    tables, offset = [], 0
    for mat, count, bits in groups:
        size = 1 << bits
        lengths = []
        for rows, cols in matrices[mat:mat+count]:
            assert rows % size == 0
            lengths.append(rows // size * cols)
        assert len(lengths) == count and all(lengths)
        tables.append(f"T.Table{{{mat}n,{size}n,{offset}n,[{nums(lengths)}]}}")
        offset += sum(lengths)
    assert offset == fields["u3"]
    lists = [nums(fields.values()), nums(limbs), ",".join(segments[x] for x in SEGMENTS), ",".join(tables)]
    return list(fields), "T.Shape{" + ",".join("["+s+"]" for s in lists) + "}"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("exports", type=Path)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    path = ROOT / "src/head_catalog.bend"
    out = ["# Generated by scripts/head-profile.py from the pinned public planner.", "import Base",
           "import ./head_types.bend as T", "import ./plan_types.bend as P", "",
           "def select(p: P.Profile) -> T.Shape:", "  match p:"]
    fields = None
    for folder, name in PROFILES:
        names, value = profile(args.exports / folder / "head.tsv")
        assert fields is None or fields == names
        fields = names
        out.append(f"    case P.{name}{{}}: {value}")
    for i, name in enumerate(fields):
        out += ["", f"def {name}(s: T.Shape) -> Nat: T.field(s,{i}n)"]
    data = "\n".join(out) + "\n"
    if args.check:
        if data != path.read_text():
            raise ValueError("head layout differs from public planner")
    else:
        path.write_text(data)


if __name__ == "__main__":
    main()
