#!/usr/bin/env python3
"""Compile public R11.1 forest shapes and R11.2 coin sites into Bend data."""
import argparse
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src/segment_geometry.bend"


def literal(n):
    if n < 1 << 32:
        return f"{n}n"
    return f"Nat.add(Nat.mul({n >> 32}n,P2.pow2(32n)),{n % (1 << 32)}n)"


def descriptor(name, shift):
    if name.startswith("R"):
        return "T.Range{}"
    mapping = {"FC": "Clamp", "FS": "Sigmoid", "FL": "Gate", "FEa": "HeadExp",
               "FEb": "HeadExp", "WH": "Window"}
    if name in mapping:
        return "T." + mapping[name] + "{}"
    for prefix, function in (("KFD", "KernelExp"), ("KR", "KernelRange")):
        if name.startswith(prefix) and 0 <= shift < 16:
            return f"T.{function}{{{1 << shift}n}}"
    raise ValueError(f"unknown packed table {name}")


def profile(folder):
    forests = OrderedDict()
    for line in (folder / "forests.tsv").read_text().splitlines():
        fields = line.split("\t")
        if fields[0] == "forest":
            key = fields[1], fields[2]
            if key in forests:
                raise ValueError(f"repeated {key}")
            dims = list(map(int,fields[3:]))
            calls = []
            forests[key] = (dims,calls)
        else:
            name, *words = fields[1:]
            k, first, iota, t0, pad, count, shift = map(int, words)
            if t0 >= 1 << k or max(first, iota, count, pad) >= 1 << 48:
                raise ValueError("invalid public call shape")
            calls.append(f"T.Call{{{descriptor(name,shift)},{k}n,{first}n,{iota}n,{literal(pad)},{count}n}}")
    rows = [line.split("\t") for line in (folder / "proof.first.rounds.tsv").read_text().splitlines()]
    actions = []
    cursor = 0
    forest_names = iter(forests)
    for i,row in enumerate(rows):
        name, scope = row[:2]
        if name == "LKP shift":
            key = next(forest_names)
            if ("smallness test" in scope) != (key[1] == "digits"):
                raise ValueError(f"wrong scope for {key}")
            stop = i + 1
            while stop < len(rows) and (rows[stop][1] == scope or rows[stop][1].startswith(scope + ", ")):
                stop += 1
            if key[1] == "main":
                start = i
            # One free entry per sent field scalar of PSC (R13.16). The frame's
            # send answers and commitment roots are separate public messages.
            slots = sum(int(r[5]) // 24 for r in rows[i:stop] if r[0].startswith("PSC "))
            fields,calls = forests[key]
            dims,latest_slot = fields[:-1],fields[-1]
            slot = sum(int(r[5]) // 24 for r in rows[start:i] if r[0].startswith("PSC ") or r[0] == "BAT-sigma")
            # The head finishes its weight merge after the smallness forest.
            if (key[0] != "H" and slot != latest_slot) or slot > latest_slot:
                raise ValueError(f"{key}: unexpected mask slot budget")
            definition = "T.Forest{" + ",".join(literal(x) for x in dims) + ",[" + ",".join(calls) + "]}"
            actions.append(("forest",i-cursor,stop-i,slot,slots,definition))
            cursor = stop
        elif name == "PSC epsilon" and scope.endswith(", terms"):
            actions.append(("coin",i-cursor))
            cursor = i+1
    if next(forest_names,None) or any(a[1] < 0 for a in actions):
        raise ValueError("incomplete or overlapping segment arithmetic")
    return actions


def generate(folder):
    lines = ["# Generated by scripts/segment-geometry.py from the public configuration.",
             "import Base", "import ./segment_tables.bend as T", "import ./plan_types.bend as P", "import ./pow2.bend as P2", "",
             "type Action is Data:", "  Forest{skip: Nat, rounds: Nat, slot: Nat, slots: Nat, shape: T.Forest}",
             "  TermsCoin{skip: Nat}", "", "def Actions() -> Data: List<&2,Action>", ""]
    definitions = {}
    functions = []
    for name, short in (("accepted-proof","small"),("accepted-proof-clipped-gap","small_clip"),
                        ("full-size","full"),("full-size-clipped-gap","full_clip")):
        actions = profile(folder / name)
        got = []
        for kind,*info in actions:
            if kind == "coin":
                got.append("TermsCoin{" + literal(info[0]) + "}")
            else:
                skip,length,slot,slots,definition = info
                f = definitions.setdefault(definition,"forest_" + str(len(definitions)))
                got.append(f"Forest{{{skip}n,{length}n,{slot}n,{slots}n,{f}()}}")
        functions += [f"def {short}() -> Actions:", "  ["+",\n   ".join(got)+"]", ""]
    for val,name in definitions.items():
        lines += [f"def {name}() -> T.Forest:", "  " + val, ""]
    return "\n".join(lines + functions + ["def select(profile: P.Profile) -> Actions:", "  match profile:",
        "    case P.SmallExact{}: small()", "    case P.SmallClipped{}: small_clip()",
        "    case P.FullExact{}: full()", "    case P.FullClipped{}: full_clip()", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("exports",type=Path)
    parser.add_argument("--check",action="store_true")
    args = parser.parse_args()
    source = generate(args.exports)
    if args.check:
        if source != SRC.read_text():
            raise SystemExit("model forest geometry differs from the pinned public configuration")
    else:
        SRC.write_text(source)
