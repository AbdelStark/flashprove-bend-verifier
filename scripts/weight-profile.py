#!/usr/bin/env python3
"""Emit H821 row/column placement for the four admitted model configurations."""
import argparse
import csv
from math import prod
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "src/weight_catalog.bend"


def parse(path):
    with path.open() as source:
        lines = iter(csv.reader(source, delimiter="\t"))
        title, width, rows, alignment = next(lines)
        assert title == "layout"
        units = []
        for row in lines:
            if row[0] == "unit":
                units.append((list(map(int, row[1:])), []))
            else:
                tag, name, cls, high, *values = row
                assert tag == "group" and cls in {"A", "E"} and name.isalpha()
                units[-1][1].append((name, cls, int(high), *map(int, values)))
    offset = 0
    for (_, _, digits, ncb, start, count), groups in units:
        assert start == offset and 0 < ncb <= int(width)
        assert count == digits * prod(group[-1] for group in groups)
        offset += count
    block = int(alignment)
    assert block in (32, 2048) and (offset + block - 1) // block * block == int(rows)
    return int(width), int(rows), units


def n(values):
    return ",".join(f"{value}n" for value in values)


def render(name, plan):
    width, rows, units = plan
    lines = []
    names = []
    for index, (fields, groups) in enumerate(units):
        fun = f"{name}_unit_{index}"
        names.append(fun + "()")
        parts = []
        for group, cls, high, *values in groups:
            flag = "True{}" if high else "False{}"
            parts.append(f'G.Group{{"{group}",G.{cls}{{}},{flag},{n(values)}}}')
        lines += [f"def {fun}() -> G.WeightUnit:", f"  G.WeightUnit{{{n(fields)},[{','.join(parts)}]}}", ""]
    lines += [f"def {name}() -> G.Layout:", f"  G.Layout{{{width}n,{rows}n,[{','.join(names)}]}}", ""]
    return lines


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("exports", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lines = ["# Generated by scripts/weight-profile.py from configuration-only planner data.",
             "import Base", "import ./weight_types.bend as G", ""]
    for model, folder in [("small", "accepted-proof"), ("full", "full-size")]:
        base = parse(args.exports / folder / "weights.tsv")
        assert base == parse(args.exports / (folder + "-clipped-gap") / "weights.tsv")
        lines.extend(render(model, base))
    content = "\n".join(lines)
    if args.check:
        if DEST.read_text() != content:
            raise ValueError("weight layout differs from the public planner")
    else:
        DEST.write_text(content)


if __name__ == "__main__":
    main()
