#!/usr/bin/env python3
"""Build H821 R13.12 key tree schedules from the configuration planner's public metadata."""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/key_stage_geometry.bend"
CHAINS = ("key.one-time", "key.shared", "key.second")


def rows(path):
    with path.open() as source:
        return list(csv.reader(source, delimiter="\t"))


def path_bound(depth, draws):
    if not depth:
        return 0
    t = min(draws, 1 << (depth - 1))
    a = t.bit_length() - 1
    return t * (depth - a - 1) + (2 << a) - t


def shape(three, draws, query_depth):
    (sym, name, _, symbols, *_), (salt, name2, _, salts, *_), (path, name3, _, paths, *_) = three
    if (sym, salt, path) != ("opened symbols", "salts", "paths") or name != name2 or name != name3:
        raise ValueError(f"incomplete opening {name}")
    depths = [d for d in range(query_depth + 1) if 32 * path_bound(d, draws) == int(paths)]
    if len(depths) != 1:
        raise ValueError(f"ambiguous depth for {name}: {depths}")
    width, rem = divmod(int(symbols), 8 * draws)
    salt_size, salt_rem = divmod(int(salts), draws)
    if rem or salt_rem or not width or salt_size != 40:
        raise ValueError(f"unsupported opening geometry for {name}")
    return name, (depths[0], width, salt_size)


def check_location(name, role):
    if not (name.endswith(", " + role) or name == "table, table" and role == "table"):
        raise ValueError(f"unexpected opening for {role}: {name}")


def render_profile(folder):
    # R13.12, in increasing place. These labels come from the public protocol
    # planner. A new tree, order, or split structure requires an explicit review.
    anchors = {"ranges": [(1, "tree of multiplicities of the ranges' look-ups; fold mask")],
               "folded row": [(0, "tree of the folded row; fold mask"),
                              (2, "tree of the mask of the split between Omega and the folded row")],
               "table": [(None, "table")]}
    shapes = {}
    groups = []
    for chain in CHAINS:
        rounds = [r for r in rows(folder / (chain + ".rounds.tsv")) if r[0] in ("LOC", "CS", "BASE")]
        messages = rows(folder / (chain + ".messages.tsv"))
        opening_rows = [i for i, row in enumerate(messages) if row[0] == "opened symbols"]
        openings = iter([messages[i:i+3] for i in opening_rows])
        if chain == "key.one-time":
            count_ranges = len(rounds)
            next_place = 2
        elif chain == "key.shared":
            count_folds = sum(row[1].startswith("folded row,") for row in rounds)
            omega_mask = count_folds + 2
            anchors["Omega"] = [(1, "tree of Omega"), (2, "tree of the mask of the split between Omega and the folded row"), (omega_mask, "fresh mask")]
            next_place = 3
        else:
            anchors["a request's own test"] = [(0, "tree of a request's masks"), (count_ranges+1, "tree of W; fold mask"), (count_ranges+2, "tree of Omega")]
            next_place = count_ranges + 3
        table = []
        for row in rounds:
            number, scope = row[0], row[1]
            group = scope.split(",")[0]
            first = scope.endswith(", stage 1") or number == "LOC"
            if first:
                roles = anchors[group]
            else:
                roles = [(next_place, "switch oracle")]
                next_place += 1
            if group == "Omega" and first:
                if next_place != omega_mask:
                    raise ValueError("unexpected shared key stages")
                next_place += 1
            required = []
            for place, role in roles:
                name, dims = shape(next(openings), int(row[10]), int(row[11]))
                check_location(name, role)
                if not name.startswith(scope.replace(", columns", "") + ","):
                    raise ValueError(f"opening outside {scope}: {name}")
                old_key = ((chain, place) if chain != "key.second" else
                           ("key.one-time", place) if place <= count_ranges+1 else
                           ("key.shared", 1) if place == count_ranges+2 else (chain, place))
                if old_key in shapes and dims != shapes[old_key]:
                    raise ValueError(f"shape changed for {old_key}")
                shapes[old_key] = dims
                target = "Table{}" if place is None else f"Local{{{place}n}}"
                required.append(f"Tree{{{target},{dims[0]}n,{dims[1]}n,{dims[2]}n}}")
            table.append("[" + ",".join(required) + "]")
        if next(openings, None) is not None:
            raise ValueError(f"unused openings for {chain}")
        groups.append(table)
    return groups


def generate(exports):
    source = ["# Generated by scripts/key-geometry.py from configuration-only H821 plans.",
              "import Base", "import ./plan_types.bend as P", "",
              "type Target is Data:", "  Table{}", "  Local{place: Nat}", "",
              "type Tree is Data:", "  Tree{target: Target, depth: Nat, width: Nat, salt: Nat}", "",
              "def Schedule() -> Data:", "  List<&2,List<&2,Tree>>", ""]
    body = []
    for folder, size in (("accepted-proof", "small"), ("full-size", "full")):
        regular = render_profile(exports / folder)
        if regular != render_profile(exports / (folder + "-clipped-gap")):
            raise ValueError("clipped schedule changed")
        body += [f"def {size}(chain: P.Chain) -> Schedule:", "  match chain:"]
        for name, queue in zip(("KeyOnce", "KeyShared", "KeySecond"), regular):
            body += [f"    case P.{name}{{}}:", "      [" + ",\n       ".join(queue) + "]"]
        body += ["    case _: []", ""]
    return "\n".join(source + body + [
        "def schedule(profile: P.Profile, chain: P.Chain) -> Schedule:", "  match profile:",
        "    case P.SmallExact{}: small(chain)", "    case P.SmallClipped{}: small(chain)",
        "    case P.FullExact{}: full(chain)", "    case P.FullClipped{}: full(chain)", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("exports", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate(args.exports)
    if args.check:
        if SOURCE.read_text() != output:
            raise SystemExit("key opening geometry differs from the pinned configuration export")
    else:
        SOURCE.write_text(output)
